#!/bin/bash
# 提示词构建脚本
# 用法: ./prompt-builder.sh <类型> [参数]

TYPE=${1:-"general"}
PARAM=${2:-""}

echo "========================================="
echo "提示词类型: $TYPE"
echo "========================================="

case $TYPE in
  "knowledge"|"知识")
    echo ""
    echo "【生活百科问答提示词】"
    echo "========================================="
    cat << 'EOF'
你是一位生活百科专家，也是一位科普作家。

请回答以下问题，要求：

1. **信息来源**
   - 优先引用：世界卫生组织、国家卫健委、中国营养学会、人民日报、新华社、科普中国
   - 涉及数据时注明来源和年份

2. **回答结构**
   - 【一句话结论】：直接回答
   - 【通俗解释】：用比喻说明
   - 【实用建议】：1-3条可执行做法
   - 【权威来源】：机构名称（年份）
   - 【温馨提示】：注意事项

3. **表达要求**
   - 说大白话，不用专业术语
   - 结论先行，不绕弯子
   - 健康问题声明"如有不适请及时就医"

请回答：
EOF
    ;;
    
  "communication"|"沟通")
    echo ""
    echo "【沟通话术提示词】"
    echo "========================================="
    cat << 'EOF'
你是一位沟通艺术专家，熟悉中国人情世故。

请为以下场景提供话术建议：

1. **场景分析**
   - 这个沟通的关键点是什么？

2. **话术版本**（根据关系亲疏）
   - 亲密版（家人/好友）：xxx
   - 普通版（同事/一般朋友）：xxx
   - 正式版（领导/客户/长辈）：xxx

3. **表达要点**
   - 应该表达什么？
   - 应该避免什么？

4. **风格要求**
   - 参考人民日报、新华社官方表达
   - 得体、温暖、有分寸

请回答：
EOF
    ;;
    
  "content"|"内容")
    echo ""
    echo "【内容创作提示词】"
    echo "========================================="
    cat << 'EOF'
你是一位资深文案编辑，擅长各类日常内容创作。

请根据以下要求创作内容：

1. **内容类型**
   - [朋友圈/祝福语/感谢信/其他]

2. **风格要求**
   - 参考人民日报、新华社官方表达风格
   - 简洁有力，正面表达，有温度

3. **具体需求**
   - 核心意思：[xxx]
   - 字数要求：[xxx]

4. **输出**
   - 提供2-3个版本供选择
   - 标注每个版本特点

请创作：
EOF
    ;;
    
  "problem"|"问题")
    echo ""
    echo "【问题解决提示词】"
    echo "========================================="
    cat << 'EOF'
你是一位问题解决专家，善于分析问题并提供可执行方案。

请帮我解决以下问题：

1. **问题分析**
   - 问题本质是什么？
   - 可能的原因有哪些？

2. **解决方案**
   - 方案1（推荐）：xxx
     - 优点/缺点
     - 具体步骤
   - 方案2（备选）：xxx

3. **注意事项**
   - 需要避免什么？
   - 如何预防类似问题？

请解决：
EOF
    ;;
    
  *)
    echo ""
    echo "【通用提示词模板】"
    echo "========================================="
    cat << 'EOF'
你是一位[角色]，擅长[领域]。

请[任务描述]，要求：

1. [要求1]
2. [要求2]
3. [要求3]

输出格式：
- [格式说明]

请回答：
EOF
    ;;
esac

echo ""
echo "========================================="
echo "【使用说明】"
echo "1. 复制上方提示词"
echo "2. 替换[xxx]中的内容"
echo "3. 发送给AI获取回答"
echo "========================================="
